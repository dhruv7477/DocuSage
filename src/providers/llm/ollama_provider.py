"""
src/providers/llm/ollama_provider.py
─────────────────────────────────────
Ollama LLM provider — runs LLaMA 3.3 (or any Ollama model) locally.

Ollama exposes an OpenAI-compatible /chat/completions endpoint as well as
its native API. We use httpx directly against the native API for:
- Streaming with proper SSE chunk parsing
- Clean error messages
- No heavyweight SDK dependency

Default model: llama3.3:70b
Runs on: CPU (slow but works) or GPU (fast, recommended for prod)
"""

import json
from collections.abc import AsyncIterator

import httpx

from src.core.exceptions import LLMProviderError
from src.core.logger import get_logger
from src.providers.llm.base import BaseLLMProvider, LLMConfig, LLMMessage, LLMResponse

log = get_logger(__name__)


class OllamaProvider(BaseLLMProvider):
    """
    LLM provider backed by a locally running Ollama instance.

    Ollama must be running and the model must be pulled before use:
        ollama pull llama3.3:70b
    """

    def __init__(self, base_url: str, model: str, timeout: int = 120) -> None:
        self._base_url = base_url.rstrip("/")
        self._model = model
        self._timeout = timeout
        # Single shared async client — connection pooling
        self._client = httpx.AsyncClient(
            base_url=self._base_url,
            timeout=httpx.Timeout(timeout, connect=10.0),
        )

    @property
    def provider_name(self) -> str:
        return f"ollama:{self._model}"

    # ── Generate (non-streaming) ──────────────────────────────────

    async def generate(
        self,
        messages: list[LLMMessage],
        config: LLMConfig | None = None,
    ) -> LLMResponse:
        """Full response — waits for the entire generation to complete."""
        cfg = config or LLMConfig()
        payload = self._build_payload(messages, cfg, stream=False)

        try:
            resp = await self._client.post("/api/chat", json=payload)
            resp.raise_for_status()
            data = resp.json()
        except httpx.HTTPStatusError as exc:
            raise LLMProviderError(
                f"Ollama request failed: {exc.response.status_code}",
                detail=exc.response.text,
            ) from exc
        except httpx.TimeoutException as exc:
            # Reachable but slow — usually the model is still loading into RAM
            # (or the container was OOM-killed and is reloading).
            raise LLMProviderError(
                "The model timed out — it may still be loading. "
                "Give it a moment and try again.",
                detail=str(exc),
            ) from exc
        except httpx.RequestError as exc:
            raise LLMProviderError(
                "Cannot reach Ollama. Is it running?",
                detail=str(exc),
            ) from exc

        content = data.get("message", {}).get("content", "")
        usage = data.get("prompt_eval_count", 0), data.get("eval_count", 0)

        log.debug("ollama_generate", model=self._model, tokens=sum(usage))
        return LLMResponse(
            content=content,
            model=self._model,
            prompt_tokens=usage[0],
            completion_tokens=usage[1],
        )

    # ── Stream ────────────────────────────────────────────────────

    async def stream(
        self,
        messages: list[LLMMessage],
        config: LLMConfig | None = None,
    ) -> AsyncIterator[str]:
        """Yields text chunks as they are generated by Ollama."""
        cfg = config or LLMConfig()
        payload = self._build_payload(messages, cfg, stream=True)

        try:
            # Create a fresh client per stream so the connection pool
            # never carries state from a previous streaming request.
            # (The shared self._client is kept for generate/health/warmup.)
            async with httpx.AsyncClient(
                base_url=self._base_url,
                timeout=httpx.Timeout(self._timeout, connect=10.0),
            ) as _stream_client:
                async with _stream_client.stream("POST", "/api/chat", json=payload) as resp:
                    resp.raise_for_status()
                    async for line in resp.aiter_lines():
                        if not line:
                            continue
                        try:
                            chunk = json.loads(line)
                        except json.JSONDecodeError:
                            continue

                        token = chunk.get("message", {}).get("content", "")
                        if token:
                            yield token

                        if chunk.get("done"):
                            break

        except httpx.HTTPStatusError as exc:
            raise LLMProviderError(
                f"Ollama stream failed: {exc.response.status_code}"
            ) from exc
        except httpx.TimeoutException as exc:
            raise LLMProviderError(
                "The model timed out mid-response — it may still be loading. "
                "Give it a moment and try again.",
                detail=str(exc),
            ) from exc
        except httpx.RequestError as exc:
            raise LLMProviderError(
                "Cannot reach Ollama during stream.", detail=str(exc)
            ) from exc

    # ── Health ────────────────────────────────────────────────────

    async def health(self) -> bool:
        """Checks Ollama is up and the target model is available."""
        try:
            resp = await self._client.get("/api/tags", timeout=5.0)
            if resp.status_code != 200:
                return False
            models = [m["name"] for m in resp.json().get("models", [])]
            # Accept partial match (e.g. "llama3.3:70b" matches "llama3.3:70b-instruct-q4_K_M")
            return any(self._model.split(":")[0] in m for m in models)
        except Exception:
            return False

    async def warmup(self) -> None:
        """
        Load the model into Ollama's RAM without generating any text.

        Ollama keeps models loaded for `keep_alive` after the last request.
        Sending a no-prompt /api/generate at startup means the first real
        query hits an already-warm model instead of waiting 30–90 s for the
        weights to transfer from disk.
        """
        log.info("ollama_warmup_start", model=self._model)
        try:
            resp = await self._client.post(
                "/api/generate",
                json={"model": self._model, "keep_alive": "30m"},
                timeout=httpx.Timeout(self._timeout, connect=10.0),
            )
            resp.raise_for_status()
            log.info("ollama_warmup_done", model=self._model)
        except Exception as exc:
            # Non-fatal — the model will still load on first real request,
            # just with more latency.
            log.warning("ollama_warmup_failed", model=self._model, error=str(exc))

    async def close(self) -> None:
        await self._client.aclose()

    # ── Private ───────────────────────────────────────────────────

    def _build_payload(
        self, messages: list[LLMMessage], config: LLMConfig, stream: bool
    ) -> dict:
        return {
            "model": self._model,
            "messages": [{"role": m.role, "content": m.content} for m in messages],
            "stream": stream,
            "keep_alive": "30m",
            **({"format": "json"} if config.response_format == "json" else {}),
            "options": {
                "temperature": config.temperature,
                "num_predict": config.max_tokens,
                "top_p": config.top_p,
                **({"stop": config.stop_sequences} if config.stop_sequences else {}),
            },
        }
