"""
src/db/base.py
──────────────
Declarative base + reusable mixins.

TimestampMixin:  auto created_at / updated_at on every model
UUIDPrimaryKey: UUID PK using server-side gen (no Python uuid4 needed)
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    """Single declarative base — all models inherit from this."""

    pass


class TimestampMixin:
    """
    Adds created_at and updated_at to any model.
    Both are handled by PostgreSQL server — no risk of timezone drift
    from the application layer.
    """

    # Fetch server-generated values with RETURNING on INSERT and UPDATE.
    # Without this, updated_at is expired after an UPDATE flush, and the
    # next read lazy-loads it, which async sessions reject with
    # MissingGreenlet (seen as a 500 on re-upload).
    __mapper_args__ = {"eager_defaults": True}

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


class UUIDPrimaryKeyMixin:
    """
    UUID primary key generated by PostgreSQL gen_random_uuid().
    Avoids sequential integer PKs that leak row counts to clients.
    """

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )
